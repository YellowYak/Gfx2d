                direction_x = 1;
            else if (prrIndex > MathHelpers.PiOver2Index && prrIndex < MathHelpers.ThreePiOver2Index)
                direction_x = -1;

            return direction_x;
        }

        public static int GetDirectionYFromRotationIndex(int prrIndex)
        {
            int direction_y = 0;
            if (prrIndex > MathHelpers.PiIndex)
                direction_y = -1;
            else if (prrIndex > 0 && prrIndex < MathHelpers.PiIndex)
                direction_y = 1;

            return direction_y;
        }

